package com.campuspi.core;

import com.campuspi.account.ApiException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.transaction.support.TransactionSynchronizationManager;

@Component
public class BusinessNumbers {
    private final JdbcTemplate db;
    public BusinessNumbers(JdbcTemplate db){this.db=db;}
    /** Caller must create the resource in this same transaction; never reserve outside it. */
    public String nextOrder() {
        if(!TransactionSynchronizationManager.isActualTransactionActive())throw new IllegalStateException("Number allocation requires an active transaction");
        var rows=db.queryForList("SELECT counter_value FROM business_number_sequences WHERE number_type='ORDER' FOR UPDATE");
        if(rows.isEmpty())throw new ApiException(503,"订单编号服务尚未配置");
        long previous=((Number)rows.get(0).get("counter_value")).longValue();
        // Also tolerate orders generated by legacy callers before their migration to this service.
        long existing=db.queryForObject("SELECT COALESCE(MAX(CAST(SUBSTRING(order_id,6) AS UNSIGNED)),0) FROM user_orders WHERE order_id REGEXP '^ORDER[0-9]{14}$'",Long.class);
        long value=Math.max(previous,existing);
        if(value>=99_999_999_999_999L)throw new ApiException(503,"订单编号空间已用尽，需要升级编号契约");
        db.update("UPDATE business_number_sequences SET counter_value=? WHERE number_type='ORDER'",value+1);
        return "ORDER"+String.format(java.util.Locale.ROOT,"%014d",value+1);
    }
}
